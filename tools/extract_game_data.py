"""
Writes src/factoriollm/base_game.py: Factorio base-game data (no Space Age) from wube/factorio-data.

draftsman ships its data with Space Age enabled: recipes there have Space Age ingredients (the
personal roboport MK2 needs superconductors, tier 3 modules need tungsten carbide), and its signal
list includes Space Age items. This tool reads the base mod's Lua prototypes at fixed tags instead:

* recipes of the tag (2.1.24) with amounts, crafting time and category (barrel recipes are
  generated by the game at load time and are added here for the base-game fluids);
* items, fluids and virtual signals of the tag;
* prototype properties of buildable entities and of items (energy source, fuel, inventories, lab
  inputs, ammunition, speeds) that the simulator and the validator work from;
* for each older version a blueprint can come from (0.15 ... 2.0), the recipes whose ingredients or
  results differ by name from the tag (in 0.16 the military science pack needed a gun turret instead
  of walls). Older recipes are read in normal mode (not "expensive").

    uv run python tools/extract_game_data.py [--tag 2.1.24]

The Lua files are data; they are parsed with a small literal-table reader, never executed.
"""

from __future__ import annotations

import argparse
import json
import re
import urllib.request
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

OUT = Path(__file__).resolve().parent.parent / "src" / "factoriollm" / "base_game.py"
RAW = "https://raw.githubusercontent.com/wube/factorio-data/{tag}/{path}"
TREE = "https://api.github.com/repos/wube/factorio-data/git/trees/{tag}?recursive=1"
BASE_FLUIDS = ("crude-oil", "heavy-oil", "light-oil", "lubricant", "petroleum-gas", "sulfuric-acid", "water")
# Last release of each version a supported blueprint can come from (blueprint_ir accepts 0.15+).
OLD_TAGS = {"0.15": "0.15.40", "0.16": "0.16.51", "0.17": "0.17.79", "0.18": "0.18.47", "1.0": "1.0.0",
            "1.1": "1.1.110", "2.0": "2.0.72"}
ITEM_TYPES = {"item", "ammo", "capsule", "gun", "module", "tool", "item-with-entity-data", "armor", "rail-planner",
              "repair-tool", "spidertron-remote", "blueprint", "blueprint-book", "deconstruction-item",
              "upgrade-item", "selection-tool", "copy-paste-tool"}


# --- A reader for Lua table literals --------------------------------------------------------------

_TOKEN = re.compile(r"""
    (?P<ws>\s+|--\[(?P<eq>=*)\[.*?\](?P=eq)\]|--[^\n]*)
  | (?P<str>"(?:\\.|[^"\\])*"|'(?:\\.|[^'\\])*'|\[\[.*?\]\])
  | (?P<num>0x[0-9a-fA-F]+|\d+\.?\d*(?:[eE][+-]?\d+)?|\.\d+(?:[eE][+-]?\d+)?)
  | (?P<name>[A-Za-z_][A-Za-z0-9_]*)
  | (?P<op>\.\.\.|\.\.|==|~=|<=|>=|[{}()\[\]=,;.:+\-*/%^#<>])
""", re.VERBOSE | re.DOTALL)

UNKNOWN = object()  # a value the reader cannot evaluate (variables, function calls)


def tokenize(source: str) -> List[Tuple[str, str]]:
    tokens, pos = [], 0
    while pos < len(source):
        m = _TOKEN.match(source, pos)
        if not m:
            raise ValueError(f"cannot tokenize at {source[pos:pos + 40]!r}")
        pos = m.end()
        kind = m.lastgroup if m.lastgroup != "eq" else "ws"
        if m.group("ws") is not None:
            continue
        if m.group("str") is not None:
            kind = "str"
        tokens.append((kind, m.group(0)))
    return tokens


class LuaReader:
    """Evaluates table constructors, strings, numbers and simple arithmetic; anything else is UNKNOWN."""

    def __init__(self, tokens: List[Tuple[str, str]]):
        self.t, self.i = tokens, 0

    def peek(self, k: int = 0) -> Tuple[str, str]:
        return self.t[self.i + k] if self.i + k < len(self.t) else ("eof", "")

    def take(self, value: Optional[str] = None) -> Tuple[str, str]:
        tok = self.peek()
        if value is not None and tok[1] != value:
            raise ValueError(f"expected {value!r}, got {tok[1]!r} at token {self.i}")
        self.i += 1
        return tok

    def expression(self) -> Any:
        left = self.unary()
        while self.peek()[1] in ("..", "+", "-", "*", "/", "%", "^", "and", "or", "==", "~=", "<", ">", "<=", ">="):
            op = self.take()[1]
            right = self.unary()
            left = _binary(op, left, right)
        return left

    def unary(self) -> Any:
        if self.peek()[1] in ("-", "not", "#"):
            op = self.take()[1]
            value = self.unary()
            return -value if op == "-" and isinstance(value, (int, float)) else UNKNOWN
        return self.primary()

    def primary(self) -> Any:
        kind, text = self.peek()
        if text == "{":
            return self.table()
        if kind == "str":
            self.take()
            return _string(text)
        if kind == "num":
            self.take()
            return int(text, 16) if text.lower().startswith("0x") else (float(text) if any(c in text for c in ".eE") else int(text))
        if text in ("true", "false", "nil"):
            self.take()
            return {"true": True, "false": False, "nil": None}[text]
        if text == "(":
            self.take()
            value = self.expression()
            self.take(")")
            return self.suffixes(value)
        if text == "function":
            self.skip_function()
            return UNKNOWN
        if kind == "name":
            self.take()
            return self.suffixes(UNKNOWN)
        raise ValueError(f"unexpected token {text!r} at {self.i}")

    def suffixes(self, value: Any) -> Any:
        """Field access, method calls and calls: `a.b`, `a:b(...)`, `f(...)`, `f{...}`, `f"..."`."""
        while True:
            kind, text = self.peek()
            if text in (".", ":"):
                self.take()
                self.take()
                value = UNKNOWN
            elif text == "[":
                self.take()
                self.expression()
                self.take("]")
                value = UNKNOWN
            elif text == "(":
                self.take()
                while self.peek()[1] != ")":
                    self.expression()
                    if self.peek()[1] == ",":
                        self.take()
                self.take(")")
                value = UNKNOWN
            elif text == "{" or kind == "str":
                self.primary()
                value = UNKNOWN
            else:
                return value

    def skip_function(self) -> None:
        depth = 0
        while True:
            kind, text = self.take()
            if kind != "name":
                continue
            if text in ("function", "do", "then", "repeat"):
                depth += 1
            elif text == "elseif":
                depth -= 1  # its `then` continues the same block
            elif text in ("end", "until"):
                depth -= 1
                if depth == 0:
                    return

    def table(self) -> Any:
        self.take("{")
        array: List[Any] = []
        fields: Dict[Any, Any] = {}
        while self.peek()[1] != "}":
            if self.peek()[0] == "name" and self.peek(1)[1] == "=":
                key = self.take()[1]
                self.take("=")
                fields[key] = self.expression()
            elif self.peek()[1] == "[":
                self.take()
                key = self.expression()
                self.take("]")
                self.take("=")
                value = self.expression()
                if key is not UNKNOWN:
                    fields[key] = value
            else:
                array.append(self.expression())
            if self.peek()[1] in (",", ";"):
                self.take()
        self.take("}")
        if fields and array:
            fields.update({i + 1: v for i, v in enumerate(array)})
            return fields
        return fields if fields else array


def _string(text: str) -> str:
    if text.startswith("[["):
        return text[2:-2]
    return bytes(text[1:-1], "utf-8").decode("unicode_escape")


def _binary(op: str, left: Any, right: Any) -> Any:
    if op == ".." and isinstance(left, (str, int, float)) and isinstance(right, (str, int, float)):
        return f"{left}{right}"
    numbers = isinstance(left, (int, float)) and isinstance(right, (int, float))
    if numbers and op in ("+", "-", "*", "/"):
        return {"+": left + right, "-": left - right, "*": left * right, "/": left / right}[op]
    return UNKNOWN


def prototypes(source: str) -> List[Dict[str, Any]]:
    """Every literal prototype table inside `data:extend(...)` calls of a Lua file."""
    tokens = tokenize(source)
    found: List[Dict[str, Any]] = []
    for i in range(len(tokens) - 3):
        if tokens[i][1] == "data" and tokens[i + 1][1] == ":" and tokens[i + 2][1] == "extend":
            j = i + 3
            if tokens[j][1] == "(":
                j += 1
            if tokens[j][1] != "{":
                continue
            reader = LuaReader(tokens)
            reader.i = j
            value = reader.table()
            for proto in value if isinstance(value, list) else []:
                if isinstance(proto, dict) and isinstance(proto.get("type"), str) and isinstance(proto.get("name"), str):
                    found.append(proto)
    return found


# --- Recipes --------------------------------------------------------------------------------------

def _part(part: Any) -> Optional[Tuple[str, str, float]]:
    """(kind, name, amount) of an ingredient or result in any of the formats 0.15 ... 2.1 use."""
    if isinstance(part, list) and len(part) == 2 and isinstance(part[0], str):
        return ("item", part[0], float(part[1]))
    if not isinstance(part, dict) or not isinstance(part.get("name"), str):
        return None
    amount = part.get("amount")
    if not isinstance(amount, (int, float)):
        low, high = part.get("amount_min"), part.get("amount_max")
        amount = (low + high) / 2 if isinstance(low, (int, float)) and isinstance(high, (int, float)) else 1
    probability = part.get("probability", 1)
    shared = part.get("shared_probability")  # 2.1: results share one roll, each owns a [min, max) slice
    if isinstance(shared, dict) and isinstance(shared.get("min"), (int, float)) and isinstance(shared.get("max"), (int, float)):
        probability = shared["max"] - shared["min"]
    probability = probability if isinstance(probability, (int, float)) else 1
    return (str(part.get("type") or "item"), part["name"], float(amount) * float(probability))


def recipe_record(proto: Dict[str, Any]) -> Optional[Dict[str, Any]]:
    body = proto.get("normal") if isinstance(proto.get("normal"), dict) else proto
    ingredients = [_part(p) for p in body.get("ingredients") or []]
    if isinstance(body.get("results"), list):
        results = [_part(p) for p in body["results"]]
    elif isinstance(body.get("result"), str):
        count = body.get("result_count", 1)
        results = [("item", body["result"], float(count if isinstance(count, (int, float)) else 1))]
    else:
        results = []
    if any(p is None for p in ingredients + results):
        return None
    time = body.get("energy_required", 0.5)
    record = {
        "ingredients": {name: _round(amount) for _, name, amount in ingredients},
        "results": {name: _round(amount) for _, name, amount in results},
        "fluids": sorted({name for kind, name, _ in ingredients + results if kind == "fluid"}),
        "time": _round(float(time if isinstance(time, (int, float)) else 0.5)),
        # 2.1 lists the recipe's categories; up to 2.0 it had one
        "category": str(proto.get("category") or (proto.get("categories") or ["crafting"])[0]),
    }
    # which fluid box of the machine a fluid uses (1-based among its input / output boxes); without
    # it the fluids take the boxes in order
    boxes = {side: {p["name"]: int(p["fluidbox_index"]) for p in body.get(key) or []
                    if isinstance(p, dict) and isinstance(p.get("fluidbox_index"), (int, float))}
             for side, key in (("in", "ingredients"), ("out", "results"))}
    if boxes["in"] or boxes["out"]:
        record["fluid_boxes"] = boxes
    if proto.get("allow_productivity"):  # productivity modules may go into its machines (intermediates)
        record["productivity"] = True
    return record


def _round(x: float) -> float:
    return round(x, 6)


def barrel_recipes() -> Dict[str, Dict[str, Any]]:
    out = {}
    for fluid in BASE_FLUIDS:
        out[f"{fluid}-barrel"] = {"ingredients": {"barrel": 1.0, fluid: 50.0}, "results": {f"{fluid}-barrel": 1.0},
                                  "fluids": [fluid], "time": 0.2, "category": "crafting-with-fluid"}
        out[f"empty-{fluid}-barrel"] = {"ingredients": {f"{fluid}-barrel": 1.0}, "results": {"barrel": 1.0, fluid: 50.0},
                                        "fluids": [fluid], "time": 0.2, "category": "crafting-with-fluid"}
    return out


# --- Download -------------------------------------------------------------------------------------

def fetch(tag: str, path: str) -> str:
    with urllib.request.urlopen(RAW.format(tag=tag, path=path), timeout=60) as response:
        return response.read().decode("utf-8")


def recipe_paths(tag: str) -> List[str]:
    with urllib.request.urlopen(TREE.format(tag=tag), timeout=60) as response:
        tree = json.loads(response.read().decode("utf-8"))["tree"]
    paths = [n["path"] for n in tree if n["path"] == "base/prototypes/recipe.lua"
             or (n["path"].startswith("base/prototypes/recipe/") and n["path"].endswith(".lua"))]
    return [p for p in paths if "demo" not in p.rsplit("/", 1)[-1]] + [p for p in paths if "demo" in p.rsplit("/", 1)[-1]]


def recipes_of(tag: str) -> Dict[str, Dict[str, Any]]:
    out: Dict[str, Dict[str, Any]] = {}
    for path in recipe_paths(tag):
        for proto in prototypes(fetch(tag, path)):
            if proto["type"] == "recipe" and not proto.get("parameter"):
                record = recipe_record(proto)
                if record is not None:
                    out[proto["name"]] = record
    return out


def _known(value: Any) -> Any:
    """The value unless the reader could not evaluate it (or any part of it)."""
    if value is UNKNOWN:
        return None
    if isinstance(value, list):
        return None if any(v is UNKNOWN for v in value) else value
    return value


def item_records(protos: List[Dict[str, Any]]) -> Dict[str, Dict[str, Any]]:
    """Per item: its prototype type, the entity it places, fuel category, burnt result, ammunition category."""
    out = {}
    for p in protos:
        if p.get("type") not in ITEM_TYPES:
            continue
        rec = {"type": p["type"]}
        for key, field in (("places", "place_result"), ("fuel_category", "fuel_category"),
                           ("burnt_result", "burnt_result"), ("ammo_category", "ammo_category")):
            value = _known(p.get(field))
            if isinstance(value, str) and value:
                rec[key] = value
        fuels = _known(p.get("fuel_categories"))  # 2.1 lists an item's fuel categories; up to 2.0 it had one
        if "fuel_category" not in rec and isinstance(fuels, list) and fuels and isinstance(fuels[0], str):
            rec["fuel_category"] = fuels[0]
        attack = _known(p.get("attack_parameters"))  # a gun (the artillery turret's cannon) fires one category
        if p["type"] == "gun" and isinstance(attack, dict) and isinstance(_known(attack.get("ammo_category")), str):
            rec["ammo_category"] = attack["ammo_category"]
        out[p["name"]] = rec
    return out


def entity_records(protos: List[Dict[str, Any]], items: Dict[str, Dict[str, Any]]) -> Dict[str, Dict[str, Any]]:
    """
    Per buildable entity (one some item places): the properties the flow simulator and the validator
    work from instead of lists of names - energy source and the fuel it burns, inventories, what a
    crafting machine can craft, what a lab or a turret takes (a turret with a gun: the gun's), belt
    and inserter speeds.
    """
    placed = {r["places"] for r in items.values() if "places" in r}
    out = {}
    for p in protos:
        name = p.get("name")
        if name not in placed or not isinstance(p.get("type"), str):
            continue
        rec: Dict[str, Any] = {"type": p["type"]}
        energy = _known(p.get("energy_source"))
        if isinstance(energy, dict) and isinstance(_known(energy.get("type")), str):
            rec["energy"] = energy["type"]
            cats = _known(energy.get("fuel_categories")) or ([energy["fuel_category"]] if isinstance(
                _known(energy.get("fuel_category")), str) else None)
            if energy["type"] == "burner":
                rec["fuel_categories"] = cats or ["chemical"]  # the game's default fuel category
                if isinstance(_known(energy.get("burnt_inventory_size")), (int, float)) and energy["burnt_inventory_size"]:
                    rec["burnt_inventory"] = int(energy["burnt_inventory_size"])
        attack = _known(p.get("attack_parameters"))
        if isinstance(attack, dict):
            ammo = _known(attack.get("ammo_categories")) or ([attack["ammo_category"]] if isinstance(
                _known(attack.get("ammo_category")), str) else None)
            if ammo:
                rec["ammo_categories"] = ammo
            fluids = _known(attack.get("fluids"))
            if isinstance(fluids, list):
                rec["fluids"] = [f["type"] for f in fluids if isinstance(f, dict) and isinstance(f.get("type"), str)]
        gun = _known(p.get("gun"))
        if isinstance(gun, str) and "ammo_category" in items.get(gun, {}):
            rec["ammo_categories"] = [items[gun]["ammo_category"]]
        for key, field in (("crafting_categories", "crafting_categories"), ("lab_inputs", "inputs"),
                           ("resource_categories", "resource_categories")):
            value = _known(p.get(field))
            if isinstance(value, list) and all(isinstance(v, str) for v in value):
                rec[key] = value
        for key, field in (("inventory", "inventory_size"), ("source_inventory", "source_inventory_size"),
                           ("result_inventory", "result_inventory_size"), ("module_slots", "module_slots"),
                           ("crafting_speed", "crafting_speed"), ("speed", "speed"), ("max_distance", "max_distance"),
                           ("rotation_speed", "rotation_speed")):
            value = _known(p.get(field))
            if isinstance(value, (int, float)) and not isinstance(value, bool):
                rec[key] = round(float(value), 6) if isinstance(value, float) else value
        if p.get("bulk") is True:
            rec["bulk"] = True
        out[name] = rec
    return out


def prototype_paths(tag: str, folder: str) -> List[str]:
    with urllib.request.urlopen(TREE.format(tag=tag), timeout=60) as response:
        tree = json.loads(response.read().decode("utf-8"))["tree"]
    return sorted(n["path"] for n in tree if n["path"].startswith(folder) and n["path"].endswith(".lua"))


def changed(old: Dict[str, Dict[str, Any]], new: Dict[str, Dict[str, Any]]) -> List[str]:
    """Recipes of both versions whose ingredients or results differ by name."""
    return sorted(name for name, r in old.items() if name in new
                  and (set(r["ingredients"]) != set(new[name]["ingredients"])
                       or set(r["results"]) != set(new[name]["results"])))


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[1])
    parser.add_argument("--tag", default="2.1.24")
    args = parser.parse_args()

    recipes = recipes_of(args.tag)
    recipes.update(barrel_recipes())
    item_protos = prototypes(fetch(args.tag, "base/prototypes/item.lua"))
    items = sorted({p["name"] for p in item_protos if p["type"] in ITEM_TYPES} | {f"{fluid}-barrel" for fluid in BASE_FLUIDS})
    item_props = item_records(item_protos)
    entity_protos = [p for path in prototype_paths(args.tag, "base/prototypes/entity/") for p in prototypes(fetch(args.tag, path))]
    entities = entity_records(entity_protos, item_props)
    fluids = sorted(p["name"] for p in prototypes(fetch(args.tag, "base/prototypes/fluid.lua")) if p["type"] == "fluid")
    signals = sorted(p["name"] for p in prototypes(fetch(args.tag, "base/prototypes/signal.lua"))
                     if p["type"] == "virtual-signal")
    changes = {}
    for version, tag in OLD_TAGS.items():
        changes[version] = changed(recipes_of(tag), recipes)
        print(f"[*] {version} ({tag}): {len(changes[version])} recipes differ: {', '.join(changes[version])}")

    lines = [f'"""Factorio base-game data {args.tag} (generated by tools/extract_game_data.py; do not edit)."""', "",
             f'BASE_GAME_VERSION = "{args.tag}"', "",
             "# name -> ingredients / results (expected amounts), fluids among them, crafting time, category",
             "RECIPES = {"]
    for name in sorted(recipes):
        lines.append(f"    {name!r}: {recipes[name]!r},")
    lines.append("}")
    for title, values in (("ITEMS", items), ("FLUIDS", fluids), ("VIRTUAL_SIGNALS", signals)):
        lines += ["", f"{title} = frozenset({{"] + [f"    {v!r}," for v in values] + ["})"]
    lines += ["", "# Recipes whose ingredients or results differed by name in an older version (normal mode).",
              "RECIPE_CHANGES = {"]
    for version, names in changes.items():
        lines.append(f"    {version!r}: frozenset({names!r}),")
    lines.append("}")
    lines += ["", "# item -> prototype type, entity it places, fuel category, burnt result, ammunition category",
              "ITEM_PROPERTIES = {"] + [f"    {k!r}: {item_props[k]!r}," for k in sorted(item_props)] + ["}"]
    lines += ["", "# buildable entity -> prototype type, energy source and fuel categories, inventories, crafting",
              "# categories, lab inputs, ammunition categories, speeds", "ENTITIES = {"]
    lines += [f"    {k!r}: {entities[k]!r}," for k in sorted(entities)] + ["}"]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"[*] {len(recipes)} recipes, {len(items)} items, {len(fluids)} fluids, {len(signals)} virtual signals, "
          f"{len(entities)} entities -> {OUT}")


if __name__ == "__main__":
    main()
