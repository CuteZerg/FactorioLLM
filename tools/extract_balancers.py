"""
Extracts verified belt balancer templates from the canonical blueprints in the database and writes
them into the BALANCER TEMPLATES block of src/factoriollm/helpers.py.

A blueprint qualifies if it consists only of belts, underground belts and plain splitters (no
priorities / filters), all inputs enter on one side and all outputs leave on the opposite side,
and a flow simulation shows that every input is split evenly across all outputs. Throughput is
not checked. Per (inputs, outputs) the smallest template is kept for every underground reach.

    uv run python tools/extract_balancers.py            # print the summary and rewrite helpers.py
    uv run python tools/extract_balancers.py --dry-run  # summary only
"""

from __future__ import annotations

import argparse
import asyncio
import json
import re
import sys
from collections import defaultdict
from pathlib import Path
from typing import Dict, List, Optional, Tuple

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from factoriollm.blueprint_ir import entity_type, footprint  # noqa: E402

HELPERS = ROOT / "src" / "factoriollm" / "helpers.py"
BEGIN, END = "# BEGIN BALANCER TEMPLATES (generated by tools/extract_balancers.py)", "# END BALANCER TEMPLATES"
VEC = {0: (0, -1), 4: (1, 0), 8: (0, 1), 12: (-1, 0)}
UG_REACH = {"underground-belt": 5, "fast-underground-belt": 7, "express-underground-belt": 9}
KINDS = {"transport-belt": "belt", "underground-belt": "underground", "splitter": "splitter"}
MAX_IO = 8


class Template:
    def __init__(self, ents):
        self.ents = ents  # [(name, x, y, d, extras)]

    def analyse(self) -> Optional[dict]:
        ents = self.ents
        tiles: Dict[Tuple[int, int], int] = {}
        for i, (name, x, y, d, _) in enumerate(ents):
            w, h = footprint(name, d)
            for dx in range(w):
                for dy in range(h):
                    tiles[(x + dx, y + dy)] = i
        xs = [t[0] for t in tiles]
        ys = [t[1] for t in tiles]
        bbox = (min(xs), min(ys), max(xs), max(ys))

        def inside(t):
            return bbox[0] <= t[0] <= bbox[2] and bbox[1] <= t[1] <= bbox[3]

        def own_tiles(i):
            name, x, y, d, _ = ents[i]
            w, h = footprint(name, d)
            return [(x + dx, y + dy) for dx in range(w) for dy in range(h)]

        def kind(i):
            return entity_type(ents[i][0])

        def io(i):
            return ents[i][4].get("io_type", "input")

        def accepts(j, moving):
            k, d = kind(j), ents[j][3]
            if k == "splitter":
                return moving == d
            if k == "underground-belt" and io(j) == "output":
                return moving != d and (moving - d) % 16 != 8
            return (moving - d) % 16 != 8  # no head-on feeding

        # underground pairs: first same-name underground along the axis
        pair: Dict[int, int] = {}
        for i, (name, x, y, d, _) in enumerate(ents):
            if kind(i) != "underground-belt" or io(i) != "input":
                continue
            dx, dy = VEC[d]
            for k in range(1, UG_REACH.get(name, 5) + 1):
                j = tiles.get((x + dx * k, y + dy * k))
                # undergrounds of the same tier on the same axis pair up; crossing ones are ignored
                if j is not None and ents[j][0] == name and ents[j][3] % 8 == d % 8:
                    if io(j) == "output" and ents[j][3] == d:
                        pair[i] = j
                    break
            if i not in pair:
                return None

        # edges: (src, dst or ("out", tile), weight)
        edges = []
        incoming = defaultdict(int)
        for i, (name, x, y, d, _) in enumerate(ents):
            k = kind(i)
            if k == "underground-belt" and io(i) == "input":
                edges.append((i, pair[i], 1.0))
                incoming[pair[i]] += 1
                continue
            targets = []
            for tx, ty in (own_tiles(i) if k == "splitter" else [(x, y)]):
                front = (tx + VEC[d][0], ty + VEC[d][1])
                j = tiles.get(front)
                if j is None or j == i:
                    targets.append(None if inside(front) else ("out", front))
                else:
                    targets.append(j if accepts(j, d) else None)
            open_targets = [t for t in targets if t is not None]
            # a blocked splitter side sends everything to the other side; a blocked belt is a dead end
            if not open_targets or (k != "splitter" and len(open_targets) < len(targets)):
                return None
            for t in open_targets:
                edges.append((i, t, 1.0 / len(open_targets)))
                if not isinstance(t, tuple):
                    incoming[t] += 1

        # inputs: unfed belts / underground entrances, and splitter halves fed from outside
        inputs = []
        for i, (name, x, y, d, _) in enumerate(ents):
            k = kind(i)
            if k == "splitter":
                for tx, ty in own_tiles(i):
                    back = (tx - VEC[d][0], ty - VEC[d][1])
                    if back not in tiles and not inside(back):
                        inputs.append((i, (tx, ty), d))
            elif incoming[i] == 0 and not (k == "underground-belt" and io(i) == "output"):
                inputs.append((i, (x, y), d))
        outputs = sorted({e[1][1] for e in edges if isinstance(e[1], tuple)})
        if not 1 <= len(inputs) <= MAX_IO or not 1 <= len(outputs) <= MAX_IO:
            return None
        flow_dirs = {d for _, _, d in inputs}
        if len(flow_dirs) != 1:
            return None

        # flow simulation per input (iterative; balancer loops converge)
        matrix = []
        for src, _, _ in inputs:
            inflow = [0.0] * len(ents)
            out = defaultdict(float)
            for _ in range(5000):
                new = [0.0] * len(ents)
                new[src] += 1.0
                out.clear()
                for a, b, w in edges:
                    if isinstance(b, tuple):
                        out[b[1]] += w * inflow[a]
                    else:
                        new[b] += w * inflow[a]
                delta = max(abs(p - q) for p, q in zip(new, inflow))
                inflow = new
                if delta < 1e-12:
                    break
            matrix.append([out[t] for t in outputs])
        n_out = len(outputs)
        if any(abs(sum(row) - 1) > 1e-6 or any(abs(v - 1 / n_out) > 1e-6 for v in row) for row in matrix):
            return None

        reach = 1
        for i, j in pair.items():
            gap = abs(ents[i][1] - ents[j][1]) + abs(ents[i][2] - ents[j][2])
            reach = max(reach, gap)
        return {"inputs": inputs, "outputs": outputs, "flow": flow_dirs.pop(), "reach": reach, "bbox": bbox}


def normalise(ents, info) -> Tuple[List[tuple], int]:
    """Rotates the template so that items flow east with its top-left tile at (0, 0)."""
    turns = ((4 - info["flow"]) // 4) % 4
    x0, y0, x1, y1 = info["bbox"]
    out = []
    for name, x, y, d, extras in ents:
        u, v = x - x0, y - y0
        w, h = footprint(name, d)
        W, H = x1 - x0 + 1, y1 - y0 + 1
        for _ in range(turns):  # quarter turn clockwise, as in helpers._Layout.commit
            u, v, w, h, W, H = H - v - h, u, h, w, H, W
        out.append((KINDS[entity_type(name)], u, v, (d + 4 * turns) % 16, extras.get("io_type")))
    width = max(u + footprint_kind(k, d)[0] for k, u, v, d, _ in out)
    return sorted(out, key=lambda e: (e[1], e[2])), width


def footprint_kind(kind: str, d: int) -> Tuple[int, int]:
    return footprint({"belt": "transport-belt", "underground": "underground-belt", "splitter": "splitter"}[kind], d)


def sides_ok(template: List[tuple], width: int, n_in: int, n_out: int) -> bool:
    """Every input enters through the west edge and every output leaves through the east edge."""
    tiles = {}
    for k, u, v, d, io in template:
        w, h = footprint_kind(k, d)
        for du in range(w):
            for dv in range(h):
                tiles[(u + du, v + dv)] = (k, d, io)
    entries = [t for t, (k, d, io) in tiles.items() if t[0] == 0 and d == 4 and not (k == "underground" and io == "output")]
    exits = [t for t, (k, d, io) in tiles.items() if t[0] == width - 1 and d == 4 and not (k == "underground" and io == "input")]
    return len(entries) == n_in and len(exits) == n_out


async def load_rows():
    from factoriollm.database import get_connection
    conn = await get_connection()
    rows = await conn.fetch("SELECT id, title, label, ir FROM canonical_blueprints WHERE status = 'ok'")
    await conn.close()
    return rows


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[1])
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()

    rows = asyncio.run(load_rows())
    found: Dict[Tuple[int, int, int], Tuple[int, int, List[tuple], str]] = {}
    checked = 0
    for r in rows:
        ir = json.loads(r["ir"])
        if not ir or any(e[0] not in ("transport-belt", "fast-transport-belt", "express-transport-belt",
                                       "underground-belt", "fast-underground-belt", "express-underground-belt",
                                       "splitter", "fast-splitter", "express-splitter") for e in ir):
            continue
        if any(set(e[4]) - {"io_type"} for e in ir) or not any("splitter" in e[0] for e in ir):
            continue
        if re.search(r"lane|side|strict|полос", f"{r['title']} {r['label']}", re.I):
            continue  # lane balancers: the belt-level simulation cannot judge them
        checked += 1
        ents = [(n, x, y, d, ex) for n, x, y, d, ex in ir]
        info = Template(ents).analyse()
        if info is None:
            continue
        template, width = normalise(ents, info)
        n_in, n_out = len(info["inputs"]), len(info["outputs"])
        if n_in == 1 and n_out == 1 or not sides_ok(template, width, n_in, n_out):
            continue
        tier = 1 if info["reach"] <= 5 else 2 if info["reach"] <= 7 else 3
        height = max(v + footprint_kind(k, d)[1] for k, u, v, d, _ in template)
        key = (n_in, n_out, tier)
        score = (len(template), width * height)
        if key not in found or score < found[key][:2]:
            source = re.sub(r"[^\x20-\x7e]+", " ", f"{r['title']} | {r['label']}")
            found[key] = (*score, template, re.sub(r"\s+", " ", f"id={r['id']} {source}")[:90])

    # keep a higher-tier template only if it is smaller than every lower-tier one
    kept = {}
    for (n_in, n_out, tier) in sorted(found):
        lower = [kept[k] for k in kept if k[:2] == (n_in, n_out)]
        if not lower or found[(n_in, n_out, tier)][0] < min(x[0] for x in lower):
            kept[(n_in, n_out, tier)] = found[(n_in, n_out, tier)]

    print(f"belt-only blueprints checked: {checked}; templates kept: {len(kept)}")
    for (n_in, n_out, tier), (n, area, _, src) in sorted(kept.items()):
        print(f"  {n_in}->{n_out} tier {tier}: {n} entities, area {area}  <- {src}")
    if args.dry_run:
        return

    lines = [BEGIN, "# (inputs, outputs, min belt tier 1..3): [(kind, u, v, direction, io_type)], items flow east",
             "_BALANCER_TEMPLATES = {"]
    for key, (_, _, template, src) in sorted(kept.items()):
        lines.append(f"    {key}: [  # canonical_blueprints {src}")
        cells = [f"({k!r}, {u}, {v}, {d}, {io!r})" for k, u, v, d, io in template]
        for i in range(0, len(cells), 5):
            lines.append("        " + ", ".join(cells[i:i + 5]) + ",")
        lines.append("    ],")
    lines += ["}", END]
    text = HELPERS.read_text(encoding="utf-8")
    pattern = re.compile(re.escape(BEGIN) + ".*?" + re.escape(END), re.S)
    if not pattern.search(text):
        raise SystemExit(f"marker block not found in {HELPERS}")
    HELPERS.write_text(pattern.sub(lambda _: "\n".join(lines), text), encoding="utf-8")
    print(f"[*] Wrote {len(kept)} templates to {HELPERS}")


if __name__ == "__main__":
    main()
